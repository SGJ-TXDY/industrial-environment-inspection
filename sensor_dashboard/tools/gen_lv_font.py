#!/usr/bin/env python3
"""Generate LVGL v8 bitmap fonts (lv_font_fmt_txt, 4 bpp, uncompressed).

Only the characters actually used by the UI are included: printable ASCII,
a few symbols, and every non-ASCII character found in the --source files.
Re-run after changing Chinese text in app/ui_lvgl.c:

    python3 tools/gen_lv_font.py --font /usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc --index 2

Needs Pillow. Default font is Noto Sans SC (SIL Open Font License).
"""
import argparse
import os
import re
from PIL import Image, ImageDraw, ImageFont

EXTRA = "°±×·—…%"
# name, pixel size, variable-font weight
FONTS = [("ui_font_cn_16", 16, "Regular"),
         ("ui_font_cn_20", 20, "Medium"),
         ("ui_font_cn_32", 32, "Bold")]


def charset(sources):
    chars = set(chr(c) for c in range(0x20, 0x7f)) | set(EXTRA)
    for path in sources:
        text = open(path, encoding="utf-8").read()
        # Only characters inside string literals matter for rendering.
        for literal in re.findall(r'"((?:[^"\\\n]|\\.)*)"', text):
            chars.update(c for c in literal if ord(c) > 0x7e)
    return sorted(chars, key=ord)


def load(path, size, weight, index):
    font = ImageFont.truetype(path, size, index=index)
    try:
        font.set_variation_by_name(weight)
    except (OSError, ValueError):
        pass  # static font: weight is fixed by the file
    return font


def render(font, ch, ascent, descent):
    pad = font.size
    w = font.size * 3
    h = ascent + descent + 2 * pad
    img = Image.new("L", (w, h), 0)
    origin_x, baseline = pad, pad + ascent
    ImageDraw.Draw(img).text((origin_x, baseline), ch, fill=255, font=font, anchor="ls")
    adv = font.getlength(ch)
    box = img.getbbox()
    if not box:
        return adv, 0, 0, 0, 0, b""
    x0, y0, x1, y1 = box
    pixels = img.crop(box)
    values = [round(v * 15 / 255) for v in pixels.tobytes()]
    # Rows are packed continuously, 2 pixels per byte, high nibble first.
    if len(values) % 2:
        values.append(0)
    data = bytes((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
    return adv, x1 - x0, y1 - y0, x0 - origin_x, baseline - y1, data


def write_font(out_dir, name, path, size, weight, chars, index):
    font = load(path, size, weight, index)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for ch in chars:
        adv, bw, bh, ox, oy, data = render(font, ch, ascent, descent)
        glyphs.append((ch, len(bitmap), round(adv * 16), bw, bh, ox, oy))
        bitmap += data
    if len(bitmap) >= 1 << 20 or any(g[2] >= 1 << 12 for g in glyphs):
        raise SystemExit(name + ": too large for LV_FONT_FMT_TXT_LARGE 0")

    ascii_chars = [c for c in chars if ord(c) < 0x7f]
    other = [c for c in chars if ord(c) >= 0x7f]
    lines = []
    lines.append("/* Generated by tools/gen_lv_font.py from %s, %d px %s, 4 bpp.\n"
                 " * %d glyphs. Do not edit; re-run the generator. */" %
                 (os.path.basename(path), size, weight, len(chars)))
    lines.append('#include "lvgl.h"\n')
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    if not bitmap:
        lines.append("    0x00,")
    lines.append("};\n")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for ch, index, adv, bw, bh, ox, oy in glyphs:
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
                     ".ofs_x = %d, .ofs_y = %d}, /* U+%04X */" % (index, adv, bw, bh, ox, oy, ord(ch)))
    lines.append("};\n")
    cmaps = []
    first = ord(ascii_chars[0])
    cmaps.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, "
                 ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                 ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}" % (first, len(ascii_chars)))
    if other:
        start = ord(other[0])
        if ord(other[-1]) - start >= 1 << 16:
            raise SystemExit(name + ": character range too wide for one sparse cmap")
        lines.append("static const uint16_t unicode_list[] = {")
        offsets = [ord(c) - start for c in other]
        for i in range(0, len(offsets), 12):
            lines.append("    " + ", ".join("0x%x" % o for o in offsets[i:i + 12]) + ",")
        lines.append("};\n")
        cmaps.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, "
                     ".unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = %d, "
                     ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}" %
                     (start, offsets[-1] + 1, 1 + len(ascii_chars), len(other)))
    lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    lines.append(",\n".join(cmaps))
    lines.append("};\n")
    lines.append("static lv_font_fmt_txt_glyph_cache_t cache;")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,")
    lines.append("    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = %d, .bpp = 4," % len(cmaps))
    lines.append("    .kern_classes = 0, .bitmap_format = 0, .cache = &cache")
    lines.append("};\n")
    lines.append("/* LVGL symbols (LV_SYMBOL_*) come from the built-in Montserrat fallback. */")
    lines.append("const lv_font_t %s = {" % name)
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append("    .line_height = %d, .base_line = %d," % (ascent + descent, descent))
    lines.append("    .subpx = LV_FONT_SUBPX_NONE,")
    lines.append("    .underline_position = %d, .underline_thickness = %d," %
                 (-max(1, size // 12), max(1, size // 16)))
    lines.append("    .dsc = &font_dsc,")
    lines.append("    .fallback = &lv_font_montserrat_%d," % (16 if size < 20 else 20 if size < 32 else 32))
    lines.append("};")
    with open(os.path.join(out_dir, name + ".c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(bitmap)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    p = argparse.ArgumentParser()
    p.add_argument("--font", default="C:/Windows/Fonts/NotoSansSC-VF.ttf")
    # NotoSansCJK-*.ttc holds JP/KR/SC/TC/HK faces; index 2 is Simplified Chinese.
    p.add_argument("--index", type=int, default=0)
    p.add_argument("--source", nargs="*", default=[os.path.join(root, "app", "ui_lvgl.c")])
    p.add_argument("--out", default=os.path.join(root, "app", "fonts"))
    a = p.parse_args()
    chars = charset(a.source)
    os.makedirs(a.out, exist_ok=True)
    for name, size, weight in FONTS:
        n = write_font(a.out, name, a.font, size, weight, chars, a.index)
        print("%s: %d glyphs, %d bitmap bytes" % (name, len(chars), n))


if __name__ == "__main__":
    main()
